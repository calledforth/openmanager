#!/usr/bin/env node
// Regenerates the vendored `codex app-server` protocol from the codex-cli on
// this machine (`CODEX_BIN`, else `codex` on PATH).
//
//   pnpm --filter @openmanager/codex-app-server-protocol generate
//
// Writes:
//   src/generated/  the ts-rs output of `codex app-server generate-ts --experimental`
//   src/methods.ts  the method names, as runtime values, so the client can tell
//                   a method this version knows from one it does not
//   src/version.ts  the codex-cli version the above came from
//
// The output is committed. Bump it deliberately: the surface changes weekly,
// and the decoder is written to tolerate what it does not know, not to chase
// every release. See docs/decisions/codex-app-server.md.
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'src', 'generated')
const bin = process.env.CODEX_BIN?.trim() || 'codex'
const shell = process.platform === 'win32'

const run = (args) => execFileSync(bin, args, { encoding: 'utf8', shell })

const versionLine = run(['--version']).trim()
const version = /(\d+\.\d+\.\d+\S*)/.exec(versionLine)?.[1]
if (!version) throw new Error(`Could not read a version from \`${bin} --version\`: ${versionLine}`)

rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })
run(['app-server', 'generate-ts', '--experimental', '--out', out])

// ts-rs writes extensionless relative imports (`from "./Foo"`, `from "./v2"`).
// They resolve under `moduleResolution: bundler` but not under `nodenext`,
// which is how the server typechecks the runtime's emitted declarations. So
// every relative specifier is made explicit: a file gets `.js`, a directory
// gets `/index.js`.
const explicitImports = (dir) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) {
      explicitImports(path)
      continue
    }
    if (!entry.name.endsWith('.ts')) continue
    const source = readFileSync(path, 'utf8')
    const rewritten = source.replace(/(from\s+")(\.{1,2}\/[^"]+)(")/g, (match, open, specifier, close) => {
      if (/\.(js|ts)$/.test(specifier)) return match
      const target = join(dirname(path), specifier)
      const isDir = existsSync(target) && statSync(target).isDirectory()
      return `${open}${specifier}${isDir ? '/index.js' : '.js'}${close}`
    })
    if (rewritten !== source) writeFileSync(path, rewritten)
  }
}
explicitImports(out)

const methodsOf = (file) => {
  const source = readFileSync(join(out, `${file}.ts`), 'utf8')
  const names = [...source.matchAll(/"method": "([^"]+)"/g)].map((match) => match[1])
  if (names.length === 0) throw new Error(`No methods found in ${file}.ts; did the generator change shape?`)
  return [...new Set(names)].sort()
}

const list = (name, doc, methods) =>
  `/** ${doc} */\nexport const ${name} = [\n${methods.map((m) => `  '${m}',`).join('\n')}\n] as const\n`

const header = `// GENERATED by scripts/generate.mjs from codex-cli ${version}. Do not edit by hand.\n\n`

writeFileSync(
  join(root, 'src', 'methods.ts'),
  header +
    [
      list('CLIENT_REQUEST_METHODS', 'Requests the client may send.', methodsOf('ClientRequest')),
      list('CLIENT_NOTIFICATION_METHODS', 'Notifications the client may send.', methodsOf('ClientNotification')),
      list('SERVER_REQUEST_METHODS', 'Requests the server may send, each awaiting an answer.', methodsOf('ServerRequest')),
      list('SERVER_NOTIFICATION_METHODS', 'Notifications the server may send.', methodsOf('ServerNotification')),
    ].join('\n'),
)

writeFileSync(
  join(root, 'src', 'version.ts'),
  `${header}/** The codex-cli version these types were generated from. */\nexport const CODEX_APP_SERVER_PROTOCOL_VERSION = '${version}'\n`,
)

console.log(`Generated the codex app-server protocol from codex-cli ${version} (${bin}).`)
